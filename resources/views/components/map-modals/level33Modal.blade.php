            Primary care outside Nouméa is delivered mainly by the provincial centres médico-sociaux (CMS, medico-social centers), traditionally called dispensaires. They are run by each Province’s health and social affairs department (Direction provinciale des affaires sanitaires et sociales). The DASS describes 26 provincial circonscriptions médico-sociales (medico-social districts). Secondary sources count 26 CMS holding about 42 multi-purpose local beds (lits polyvalents de proximité), plus about 23 secondary centers and infirmaries. By province, these are: Îles Loyauté, 5 dispensaires with 31 beds; Province Sud, 7 with 9 beds; Province Nord, 14 with 2 beds. In Greater Nouméa and much of the Province Sud, primary care relies mainly on private practitioners (médecins libéraux).

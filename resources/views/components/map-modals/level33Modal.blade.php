            <strong>Note:</strong> The Chambre territoriale des comptes reported in 2023 that some medico-social centers operate observation beds that were never formally authorized under the carte sanitaire, and recommended clarifying their status. For desk research, search “centre médico-social,” “CMS,” “dispensaire,” “centre médical” and “infirmerie” as possible names for this tier, and record the term the source uses. Classify these as “Provincial medico-social center (primary care)” even where a center has a few local beds.

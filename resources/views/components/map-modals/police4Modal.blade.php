        <p class="p-modal"><strong>Command level:</strong> Local Operational / Communal Tactical Command</p>

        <p class="p-modal"><strong>Typical Head Rank:</strong></p>
        <ul class="mb-3">
            <li><em>Directeur de police municipale</em> or <em>Directeur principal de police municipale</em> — used in larger municipalities or cities (such as Nouméa) where the municipal police service is substantial and led by a Category A (Senior Management/Executive) civil servant.</li>
            <li><em>Chef de service de police municipale</em> or <em>Chef de service principal de 2ème classe / 1ère classe</em> — used in mid-sized or smaller municipalities led by a Category B (Mid-Level Command/Supervisory) officer.</li>
            <li><em>Brigadier-chef principal</em> — used in smaller communes where a Category C (Senior Non-Commissioned Officer/Field Commander/Unit Leader) manages a small team of officers.</li>
        </ul>

        <p class="p-modal"><strong>Administrative Equivalent:</strong> Individual municipalities (communes) across New Caledonia, such as Nouméa, Mont-Dore, and Dumbéa.</p>

        <p class="p-modal"><strong>Role:</strong> Local officers employed directly by municipal councils. They focus on local public order, traffic control, enforcing municipal bylaws, and supporting national forces.</p>
        <p class="p-modal">Functions as the primary local proximity policing entity within a specific municipal territory, enforcing municipal regulations, securing public spaces, preventing local delinquency, and assisting state security forces (<em>Police Nationale</em> and <em>Gendarmerie Nationale</em>) during urban security operations and public gatherings.</p>

        <p class="p-modal"><strong>Responsibilities:</strong></p>
        <ul>
            <li>Enforce municipal orders, mayoral decrees, and local administrative regulations across the communal territory.</li>
            <li>Conduct visible patrols to maintain public tranquility, safety, and neighborhood security.</li>
            <li>Monitor road traffic, enforce parking regulations, and manage local road safety.</li>
            <li>Secure public gatherings, civic events, municipal facilities, and local markets.</li>
            <li>Respond to minor public order disturbances, neighborhood disputes, and local noise complaints.</li>
            <li>Conduct surveillance of public spaces using municipal CCTV network monitoring centers (<em>Centre de Supervision Urbain</em>).</li>
            <li>Report criminal offenses and public safety intelligence directly to state law enforcement authorities (<em>Police Nationale</em> or <em>Gendarmerie Nationale</em>).</li>
            <li>Assist state security forces in establishing perimeters and securing sites during emergencies or joint operations.</li>
            <li>Process lost property, handle stray animal management, and perform environmental or civil waste compliance checks.</li>
        </ul>

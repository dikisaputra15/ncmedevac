        <p class="p-modal text-justify">
            The provincial hospital level is the Centre hospitalier du Nord (CHN, Northern Hospital Center), a public hospital establishment with three sites in the Province Nord: the Pôle sanitaire du Nord in Koné (opened 2018), the Paula-Thavoavianon site in Koumac and the Raymond-Doui-Nébayes site in Poindimié. Under the emergency scheme, the CHN Koumac site is named as a facility that can provide the Niveau 3 service: the unité de proximité, d’accueil, d’orientation et de traitement des urgences (UPAOTU, local emergency reception, triage and treatment unit). It handles common emergencies and stabilizes and transfers serious cases to the CHT.
        </p>
        <p class="p-modal text-justify">
            <strong>Note:</strong> The Province Sud and Province des Îles Loyauté have no separate public hospital establishment. Their populations rely on the CHT and on provincial medico-social centers, some of which hold small numbers of short-stay beds. Deliberation 171 also allows certain provincial medical centers, and a private site in Nouméa, to perform the Niveau 3 (UPAOTU) emergency function. Record CHN sites as “Provincial level — public hospital (CHN).”
        </p>
        <ul data-info-section="role">
            <li>Provide general short-stay hospital care for the Province Nord and refer cases beyond its capability to the CHT</li>
            <li>Provide local emergency reception and stabilization (Niveau 3 UPAOTU) and coordinate transfers with the centre 15</li>
            <li>Support the medico-social centers of the Province Nord through inter-hospital and provincial agreements.</li>
        </ul>
        <p data-info-section="services"><strong>Typical Bed Capacity</strong></p>
        <ul>
            <li>About 132 beds across the three sites: Koné about 52 short-stay beds, Koumac about 42 short-stay beds, Poindimié about 38 beds (24 short-stay, 14 follow-up and rehabilitation).</li>
        </ul>
